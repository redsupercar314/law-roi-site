// Precompute the map geometry once so the browser ships no geo libraries.
// Outputs src/data/map.js: a projected U.S. outline, state hairlines, and an
// x/y for every campus. Re-run after adding schools or changing locations.
import fs from 'node:fs';
import { geoAlbersUsa, geoPath } from 'd3-geo';
import { merge, mesh } from 'topojson-client';
import { presimplify, simplify } from 'topojson-simplify';
import { SCHOOL_LOCATIONS } from '../src/data/locations.js';

const W = 975;
const H = 610;
const FRAME = 14;
const THRESHOLD = Number(process.env.SIMPLIFY ?? 0.002);

const raw = JSON.parse(fs.readFileSync('node_modules/us-atlas/states-10m.json', 'utf8'));
const geometries = raw.objects.states.geometries.filter((g) => String(g.id) !== '72'); // drop Puerto Rico
const base = {
  type: 'Topology',
  transform: raw.transform,
  arcs: raw.arcs,
  objects: { states: { type: 'GeometryCollection', geometries } },
};

const simplified = simplify(presimplify(base), THRESHOLD);
const nation = merge(simplified, simplified.objects.states.geometries);
const borders = mesh(simplified, simplified.objects.states, (a, b) => a !== b);

const projection = geoAlbersUsa().fitExtent(
  [
    [FRAME, FRAME],
    [W - FRAME, H - FRAME],
  ],
  nation,
);
const path = geoPath(projection).digits(1);

const outline = path(nation);
const states = path(borders);

const missing = [];
const xy = {};
for (const [name, loc] of Object.entries(SCHOOL_LOCATIONS)) {
  const p = projection([loc.lng, loc.lat]);
  if (!p) {
    missing.push(name);
    continue;
  }
  xy[name] = [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10];
}

console.log(`simplify=${THRESHOLD} outline=${outline.length} states=${states.length} bytes`);
console.log(`projected ${Object.keys(xy).length} schools; missing: ${missing.length ? missing.join(', ') : 'none'}`);
console.log('bounds', path.bounds(nation));

if (!process.env.DRY) {
  const body = `// Generated by scripts/build-map.mjs. Do not edit by hand.\n`
    + `export const MAP_WIDTH = ${W};\n`
    + `export const MAP_HEIGHT = ${H};\n`
    + `export const US_OUTLINE = ${JSON.stringify(outline)};\n`
    + `export const US_STATES = ${JSON.stringify(states)};\n`
    + `export const SCHOOL_XY = ${JSON.stringify(xy, null, 1)};\n`;
  fs.writeFileSync('src/data/map.js', body);
  console.log(`wrote src/data/map.js (${body.length} bytes)`);
}
